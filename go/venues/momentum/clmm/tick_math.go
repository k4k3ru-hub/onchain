package clmm

import "math/big"

// Protocol Q64/Q96 multipliers from Momentum v3 tick_math; no floating point is used.
func sqrtAtTick(tick int32) *big.Int {
	negative := tick < 0
	n := int64(tick)
	if n < 0 {
		n = -n
	}
	factors := []string{"79232123823359799118286999567", "79236085330515764027303304731", "79244008939048815603706035061", "79259858533276714757314932305", "79291567232598584799939703904", "79355022692464371645785046466", "79482085999252804386437311141", "79736823300114093921829183326", "80248749790819932309965073892", "81282483887344747381513967011", "83390072131320151908154831281", "87770609709833776024991924138", "97234110755111693312479820773", "119332217159966728226237229890", "179736315981702064433883588727", "407748233172238350107850275304", "2098478828474011932436660412517", "55581415166113811149459800483533", "38992368544603139932233054999993551"}
	shift := uint(96)
	if negative {
		shift = 64
		factors = []string{"18445821805675392311", "18444899583751176498", "18443055278223354162", "18439367220385604838", "18431993317065449817", "18417254355718160513", "18387811781193591352", "18329067761203520168", "18212142134806087854", "17980523815641551639", "17526086738831147013", "16651378430235024244", "15030750278693429944", "12247334978882834399", "8131365268884726200", "3584323654723342297", "696457651847595233", "26294789957452057", "37481735321082"}
	}
	value := new(big.Int).Lsh(big.NewInt(1), shift)
	for bit, f := range factors {
		if n&(1<<bit) != 0 {
			multiplier, _ := new(big.Int).SetString(f, 10)
			value.Mul(value, multiplier).Rsh(value, shift)
		}
	}
	if !negative {
		value.Rsh(value, 32)
	}
	return value
}
